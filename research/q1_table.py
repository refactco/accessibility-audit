"""Build the table of research question 1: the test method of each criterion, with the evidence.

Usage: python3 -I research/q1_table.py criteria/criteria.json tests/seeded-faults/faults.json research/Q1-methods-table.md [tests/seeded-faults/build/baseline-axe.json]

For each of the 55 criteria: the method in the plan, the test groups, the own
test of the engine, who decides the rest, the approved ACT rules, the axe-core
rules, and the seeded faults with the result of the axe-core baseline.
"""
import json
import os
import sys


def main(criteria_path, faults_path, out_path, baseline_path=None):
    with open(criteria_path, encoding="utf-8") as f:
        criteria = json.load(f)["criteria"]
    with open(faults_path, encoding="utf-8") as f:
        faults = json.load(f)["faults"]
    baseline = {}
    if baseline_path and os.path.exists(baseline_path):
        with open(baseline_path, encoding="utf-8") as f:
            baseline = {r["id"]: r["found"] for r in json.load(f)["rows"]}
    by_crit = {}
    for fault in faults:
        by_crit.setdefault(fault["criterion"], []).append(fault)

    lines = ["# The method of each criterion, with the evidence\n",
             "Generated by `research/q1_table.py` from `criteria/criteria.json`, `tests/seeded-faults/faults.json`, and the axe-core baseline. Do not edit by hand.\n",
             "Method: `auto` = the engine decides alone, with conditions. `auto+review` = the engine finds and measures, and the AI or a person decides the rest. `person` = the engine finds the content and a person tests it. "
             "ACT = approved ACT rules for the criterion. axe = definite rules / review rules of axe-core 4.14.0. Faults = seeded faults, with `+` when the axe-core baseline finds the fault, `~` when axe-core gives an incomplete result, and `-` when it does not find it.\n",
             "| Criterion | Level | Method | Groups | Own test of the engine | Decides the rest | ACT | axe | Faults |",
             "|---|---|---|---|---|---|---|---|---|"]
    counts = {"auto": 0, "auto+review": 0, "person": 0}
    for e in criteria:
        counts[e["method"]] += 1
        act = sum(1 for r in e.get("act_rules", []) if r.get("approved"))
        axe_d = sum(1 for r in e.get("axe_rules", []) if r.get("category") == "wcag" and "failure" in (r.get("issue_type") or ""))
        axe_r = sum(1 for r in e.get("axe_rules", []) if r.get("category") == "wcag" and "failure" not in (r.get("issue_type") or ""))
        marks = {"violation": "+", "incomplete": "~", "related": "~", "no": "-"}
        fl = ", ".join(f"{x['id'].split('-')[0]}{marks.get(baseline.get(x['id'], 'no'), '?') if baseline else ''}" for x in by_crit.get(e["id"], [])) or "-"
        decides = {"auto": "The engine", "person": "A person"}.get(e["method"])
        if e["method"] == "auto+review":
            text = (e.get("review_or_person_check") or "").lower()
            decides = "AI, person confirms the sample" if text.startswith("ai") else "A person"
        own = (e.get("automatic_test") or "-").split(". ")[0].rstrip(".")
        lines.append(f"| {e['id']} {e['name']} | {e['level']} | {e['method']} | {', '.join(e['test_groups'])} | {own} | {decides} | {act or '-'} | {axe_d} / {axe_r} | {fl} |")
    lines.append("")
    lines.append(f"Counts: auto {counts['auto']}, auto+review {counts['auto+review']}, person {counts['person']}. "
                 f"Criteria with an approved ACT rule: {sum(1 for e in criteria if any(r.get('approved') for r in e.get('act_rules', [])))}. "
                 f"Criteria with a definite axe-core rule: {sum(1 for e in criteria if any(r.get('category') == 'wcag' and 'failure' in (r.get('issue_type') or '') for r in e.get('axe_rules', [])))}. "
                 f"Criteria with a seeded fault: {len(by_crit)}.\n")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("written", out_path, counts)


if __name__ == "__main__":
    main(*sys.argv[1:])
