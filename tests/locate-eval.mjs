// The location accuracy of the skill on the seeded faults, the check of stage 4.
//
// Usage: node tests/locate-eval.mjs prepare [--detect <folder>]   writes the task list for the agents
//        node tests/locate-eval.mjs score                           compares the recorded origin and source with the fault list
//
// Each seeded fault that the engine decides gives one issue in the last detection run. The agent that runs the skill finds the origin
// and the source file of each issue in the source folder of the variant, and records them with `a11y locate`. The fault list holds
// the truth: the origin of the fault and the files that its edits changed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const mode = args[0];
const flag = (name) => { const i = args.indexOf("--" + name); return i >= 0 ? args[i + 1] : null; };
const detect = path.resolve(flag("detect") || path.join(here, "seeded-faults", "build", "tmp", "detect-full"));
const work = path.join(here, "seeded-faults", "build", "tmp", "locate");
const tasksFile = path.join(work, "tasks.json");
const faults = JSON.parse(fs.readFileSync(path.join(here, "seeded-faults", "faults.json"), "utf8")).faults;
const readIssues = (dir) => fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))) : [];

if (mode === "prepare") {
  fs.mkdirSync(work, { recursive: true });
  const tasks = [];
  for (const fault of faults) {
    if (fault.decider !== "engine") continue;
    const results = path.join(detect, fault.id);
    const issues = readIssues(path.join(results, "issues")).filter((i) => i.wcag.criterion === fault.criterion && ["new", "open", "reopened"].includes(i.status));
    if (!issues.length) { console.error(`no issue for ${fault.id}`); continue; }
    // The issue with the largest reach is the one of the fault.
    const issue = issues.sort((a, b) => b.reach.pages - a.reach.pages)[0];
    tasks.push({ fault: fault.id, criterion: fault.criterion, issue: issue.id, results, source: path.join(here, "seeded-faults", "build", fault.id), truth: { origin: fault.origin, files: [...new Set(fault.edits.map((e) => e.file))], solution: fault.solution } });
  }
  fs.writeFileSync(tasksFile, JSON.stringify(tasks, null, 1));
  console.log(JSON.stringify({ tasks: tasks.length, file: tasksFile }));
} else if (mode === "score") {
  const tasks = JSON.parse(fs.readFileSync(tasksFile, "utf8"));
  const rows = [];
  for (const t of tasks) {
    const issue = JSON.parse(fs.readFileSync(path.join(t.results, "issues", t.issue + ".json"), "utf8"));
    const files = (issue.source || []).filter((s) => s.file).map((s) => path.basename(s.file));
    const originOk = issue.origin === t.truth.origin;
    const fileOk = files.some((f) => t.truth.files.includes(f));
    const allFilesOk = t.truth.files.every((f) => files.includes(f));
    rows.push({ fault: t.fault, criterion: t.criterion, truthOrigin: t.truth.origin, origin: issue.origin, originOk, truthFiles: t.truth.files, files, fileOk, allFilesOk, solutionType: issue.solution.type, solution: issue.solution.summary, located: issue.origin !== "unknown" });
  }
  const n = rows.length, located = rows.filter((r) => r.located).length;
  const md = [`# The location accuracy of the skill on the seeded faults\n`, `Generated by \`tests/locate-eval.mjs score\` on ${new Date().toISOString().slice(0, 10)}. The skill found the origin and the source file of the issue of each seeded fault that the engine decides. The fault list gives the truth: the origin of the fault, and the files that its edits changed.\n`,
    `| Issues | Located | Origin correct | Source file correct | All source files correct | Specific solution |\n|---|---|---|---|---|---|\n| ${n} | ${located} | ${rows.filter((r) => r.originOk).length} | ${rows.filter((r) => r.fileOk).length} | ${rows.filter((r) => r.allFilesOk).length} | ${rows.filter((r) => r.solutionType === "specific").length} |\n`,
    `| Fault | Criterion | Origin: truth, found | Files: truth, found | Solution of the skill |\n|---|---|---|---|---|`];
  for (const r of rows) md.push(`| ${r.fault} | ${r.criterion} | ${r.truthOrigin}, ${r.origin}${r.originOk ? "" : " (wrong)"} | ${r.truthFiles.join(" ")}, ${r.files.join(" ") || "-"}${r.fileOk ? "" : " (wrong)"} | ${(r.solution || "").replace(/\|/g, "/").slice(0, 100)} |`);
  fs.writeFileSync(path.join(here, "seeded-faults", "location.md"), md.join("\n") + "\n");
  console.log(JSON.stringify({ issues: n, located, originCorrect: rows.filter((r) => r.originOk).length, fileCorrect: rows.filter((r) => r.fileOk).length, allFilesCorrect: rows.filter((r) => r.allFilesOk).length }));
} else {
  console.error("Usage: node tests/locate-eval.mjs prepare|score");
  process.exit(2);
}
